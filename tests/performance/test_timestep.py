"""Timeline accounting must not count a wait and its kernels twice."""
import tempfile
from pathlib import Path
import unittest

from tools.performance.timestep_report import identity, kernel_stages, overlap, source_identity, timeline, union
from tools.performance.timestep_trace import prepare


class TimestepTraceTests(unittest.TestCase):
    def test_source_receipt_rejects_a_stale_executable_even_when_it_exists(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            for file in ("Cargo.toml", "Cargo.lock", "build.rs"):
                (root / file).write_text(file)
            (root / "src").mkdir()
            source = root / "src/lib.rs"
            source.write_text("old")
            digest, _ = source_identity(root)
            binary = root / "binary"
            binary.write_bytes(digest.encode() + b"//\n// Generated by NVIDIA NVVM Compiler\nPTX\0")
            self.assertEqual(identity(root, binary)["source_sha256"], digest)
            source.write_text("new")
            with self.assertRaises(ValueError):
                identity(root, binary)

    def test_union_and_clip_include_overlapping_gpu_work_once(self):
        spans = union([(2, 8), (4, 10), (12, 16), (16, 19)])
        self.assertEqual(spans, [(2, 10), (12, 19)])
        self.assertEqual(overlap(5, 17, spans, [10, 19]), 10)
        self.assertEqual(overlap(10, 12, spans, [10, 19]), 0)
        with self.assertRaises(ValueError):
            union([(4, 3)])

    def test_waits_and_host_work_remain_disjoint_from_solver_activity(self):
        events = [
            dict(kind="range", name="complete timestep", start=0, end=10_000_000),
            dict(kind="kernel", name="solver", start=2_000_000, end=7_000_000),
            dict(kind="copy", name="2", start=8_000_000, end=9_000_000),
            dict(kind="api", name="cuStreamSynchronize", start=1_000_000, end=7_500_000),
            dict(kind="range", name="worker observation publication", start=10_000_000, end=11_000_000),
        ]
        result = timeline(events)
        self.assertEqual(result["complete_ms_per_step"], 10)
        self.assertEqual(result["solver_gpu_ms_per_step"], 6)
        self.assertEqual(result["without_solver_gpu_ms_per_step"], 4)
        wait = result["components"]["api:cuStreamSynchronize"]
        self.assertEqual(wait["inclusive_ms_per_step"], 6.5)
        self.assertEqual(wait["without_solver_gpu_ms_per_step"], 1.5)
        self.assertNotIn("range:worker observation publication", result["components"])

    def test_overlapping_timesteps_are_rejected(self):
        events = [dict(kind="range", name="complete timestep", start=0, end=20),
                  dict(kind="range", name="complete timestep", start=10, end=30)]
        with self.assertRaises(ValueError):
            timeline(events)

    def test_general_entry_attribution_requires_the_whole_launch_sequence(self):
        names = (["observe_state"] * 2 + ["solver"] + ["spatial_sort"] * 7
                 + ["solver"] + ["prefix_counts"] * 3 + ["solver"] * 51)
        self.assertEqual(len(names), 65)
        events = [dict(kind="range", name="complete timestep", start=0, end=66_000)]
        events += [dict(kind="kernel", name=name, start=i * 1000, end=i * 1000 + 500)
                   for i, name in enumerate(names)]
        result = kernel_stages(events, 8000, False)
        self.assertEqual(result["kernel_ms_per_step"]["correction"], 0.004)
        with self.assertRaises(ValueError):
            kernel_stages(events[:-1], 8000, False)
        events[5]["name"] = "solver"
        with self.assertRaises(ValueError):
            kernel_stages(events, 8000, False)

    def test_instrumentation_refuses_checkout_and_does_not_partially_edit(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            (root / "native").mkdir()
            (root / "native/bridge.cpp").write_text("unchanged")
            (root / ".git").write_text("gitdir: elsewhere")
            with self.assertRaises(ValueError):
                prepare(root)
            self.assertEqual((root / "native/bridge.cpp").read_text(), "unchanged")
            (root / ".git").unlink()
            (root / "src").mkdir()
            (root / "src/lib.rs").write_text("source drift")
            with self.assertRaises(ValueError):
                prepare(root)
            self.assertEqual((root / "native/bridge.cpp").read_text(), "unchanged")


if __name__ == "__main__":
    unittest.main()
