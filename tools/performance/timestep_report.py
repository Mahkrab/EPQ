"""Recompute paired viewer results and disjoint CUDA timeline contributions.

The timeline reader retains inclusive API durations separately from GPU activity
and from time without solver GPU activity. Those quantities must not be added.
"""
from __future__ import annotations

import argparse
from bisect import bisect_right
import csv
import hashlib
import json
import math
from pathlib import Path
import sqlite3
import statistics

from .live_viewer import summarise


def source_identity(root: Path) -> tuple[str, dict]:
    """Reproduce the build script's source digest without invoking Cargo."""
    paths = [Path(name) for name in ("Cargo.toml", "Cargo.lock", "build.rs")]
    for directory in ("src", "native", "build_support", "scenes", "config"):
        paths.extend(p.relative_to(root) for p in (root / directory).rglob("*") if p.is_file())
    digest = hashlib.sha256()
    files = {}
    for path in sorted(paths):
        data = (root / path).read_bytes()
        digest.update(str(path).encode())
        digest.update(b"\0")
        digest.update(len(data).to_bytes(8, "little"))
        digest.update(data)
        files[str(path)] = dict(bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
    return digest.hexdigest(), files


def identity(root: Path, binary: Path) -> dict:
    expected, files = source_identity(root)
    data = binary.read_bytes()
    if expected.encode() not in data:
        raise ValueError("executable does not contain this source digest; force a fresh build")
    start = data.find(b"//\n// Generated by NVIDIA NVVM Compiler")
    if start < 0:
        raise ValueError("embedded CUDA PTX is missing")
    ptx = data[start:data.index(b"\0", start) + 1]
    return dict(source_sha256=expected, files=files, executable_sha256=hashlib.sha256(data).hexdigest(),
                ptx_bytes=len(ptx), ptx_sha256=hashlib.sha256(ptx).hexdigest())


def union(intervals: list[tuple[int, int]]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for start, end in sorted(intervals):
        if end < start:
            raise ValueError("negative timeline interval")
        if result and start <= result[-1][1]:
            result[-1] = (result[-1][0], max(end, result[-1][1]))
        else:
            result.append((start, end))
    return result


def overlap(start: int, end: int, spans: list[tuple[int, int]], ends: list[int]) -> int:
    total = 0
    for index in range(bisect_right(ends, start), len(spans)):
        left, right = spans[index]
        if left >= end:
            break
        total += max(0, min(right, end) - max(left, start))
    return total


def comparison(root: Path, prefix: str, candidate: str) -> dict:
    result = {}
    metrics = ("solver_ms_per_step", "simulated_s_per_wall_s", "complete_run_wall_s",
               "presentation_fps", "frame_p95_ms", "frame_p99_ms")
    for count in (8000, 32000, 110592):
        samples = {variant: [] for variant in ("control", candidate)}
        for pair in range(4):
            for variant in samples:
                directory = root / f"{prefix}-{count}-p{pair}-{variant}"
                stored = json.loads((directory / "summary.json").read_text())
                measured = summarise(directory / "frames.csv")
                for key in metrics:
                    if key in measured and not math.isclose(measured[key], stored[key], rel_tol=1e-12):
                        raise ValueError(f"changed {key}: {directory.name}")
                with (directory / "frames.csv").open(newline="") as stream:
                    rows = list(csv.DictReader(stream))
                if int(rows[-1]["step"]) != 1200 or rows[-1]["status"] != "Completed":
                    raise ValueError(f"incomplete fixed workload: {directory.name}")
                if stored["particle_renderer"] != "impostor":
                    raise ValueError("comparison renderer differs")
                if pair:
                    samples[variant].append({k: stored[k] for k in metrics})
        summary = {}
        for variant, values in samples.items():
            summary[variant] = {key: dict(median=statistics.median(x[key] for x in values),
                                         minimum=min(x[key] for x in values),
                                         maximum=max(x[key] for x in values)) for key in metrics}
        pairs = [dict(pair=i + 1,
                      viewer_ratio=b["simulated_s_per_wall_s"] / a["simulated_s_per_wall_s"],
                      solver_ratio=a["solver_ms_per_step"] / b["solver_ms_per_step"],
                      command_ratio=a["complete_run_wall_s"] / b["complete_run_wall_s"])
                 for i, (a, b) in enumerate(zip(samples["control"], samples[candidate]))]
        result[str(count)] = dict(samples=samples, summary=summary, pairs=pairs)
    return result


def export_timeline(database: Path) -> list[dict]:
    """Export anonymous intervals; native reports retain machine details privately."""
    c = sqlite3.connect(f"file:{database}?mode=ro", uri=True)
    try:
        events = []
        for start, end, name in c.execute("SELECT n.start,n.end,coalesce(n.text,s.value) "
                "FROM NVTX_EVENTS n LEFT JOIN StringIds s ON n.textId=s.id "
                "WHERE n.end IS NOT NULL AND n.eventType=59"):
            events.append(dict(kind="range", name=name, start=start, end=end))
        for start, end, name in c.execute("SELECT k.start,k.end,s.value FROM CUPTI_ACTIVITY_KIND_KERNEL k "
                                         "JOIN StringIds s ON s.id=k.shortName"):
            events.append(dict(kind="kernel", name=name, start=start, end=end))
        for start, end, size, kind in c.execute("SELECT start,end,bytes,copyKind FROM CUPTI_ACTIVITY_KIND_MEMCPY"):
            events.append(dict(kind="copy", name=str(kind), start=start, end=end, bytes=size))
        for start, end in c.execute("SELECT start,end FROM CUPTI_ACTIVITY_KIND_MEMSET"):
            events.append(dict(kind="memset", name="reset", start=start, end=end))
        for start, end, name in c.execute("SELECT k.start,k.end,s.value FROM CUPTI_ACTIVITY_KIND_RUNTIME k "
                                         "JOIN StringIds s ON s.id=k.nameId"):
            events.append(dict(kind="api", name=name, start=start, end=end))
    finally:
        c.close()
    steps = [x for x in events if x["name"] == "complete timestep" and x["kind"] == "range"]
    if not steps:
        raise ValueError("trace lacks complete timestep ranges")
    first, last = min(x["start"] for x in steps), max(x["end"] for x in steps)
    last = max([last] + [x["end"] for x in events if x["kind"] == "range"
                        and x["name"] == "worker observation publication" and x["start"] >= first])
    # Keep worker publication immediately after the final solver return as well.
    retained = [x for x in events if x["end"] >= first and x["start"] <= last]
    for event in retained:
        event["start"] -= first
        event["end"] -= first
    return sorted(retained, key=lambda x: (x["start"], x["end"]))


def timeline(events: list[dict]) -> dict:
    steps = sorted((x for x in events if x["kind"] == "range" and x["name"] == "complete timestep"),
                   key=lambda x: x["start"])
    if not steps or any(a["end"] > b["start"] for a, b in zip(steps, steps[1:])):
        raise ValueError("missing or overlapping complete timesteps")
    gpu = union([(x["start"], x["end"]) for x in events if x["kind"] in ("kernel", "copy", "memset")])
    ends = [b for _, b in gpu]
    total = sum(x["end"] - x["start"] for x in steps)
    active = sum(overlap(x["start"], x["end"], gpu, ends) for x in steps)
    step_spans = [(x["start"], x["end"]) for x in steps]
    step_ends = [b for _, b in step_spans]
    by_kind: dict[str, dict] = {}
    for event in events:
        duration = overlap(event["start"], event["end"], step_spans, step_ends)
        if not duration:
            continue
        label = event["kind"] + ":" + event["name"]
        entry = by_kind.setdefault(label, dict(count=0, inclusive_ns=0, without_solver_gpu_ns=0))
        entry["count"] += 1
        entry["inclusive_ns"] += duration
        if event["kind"] in ("api", "range"):
            # Clip each event to the step union before removing solver activity.
            for index in range(bisect_right(step_ends, event["start"]), len(steps)):
                a, b = step_spans[index]
                if a >= event["end"]:
                    break
                a, b = max(a, event["start"]), min(b, event["end"])
                entry["without_solver_gpu_ns"] += b - a - overlap(a, b, gpu, ends)
    scale = 1e6 * len(steps)
    return dict(steps=len(steps), complete_ms_per_step=total / scale,
                solver_gpu_ms_per_step=active / scale, without_solver_gpu_ms_per_step=(total - active) / scale,
                components={key: dict(count_per_step=value["count"] / len(steps),
                                      inclusive_ms_per_step=value["inclusive_ns"] / scale,
                                      without_solver_gpu_ms_per_step=value["without_solver_gpu_ns"] / scale)
                            for key, value in sorted(by_kind.items())})


def kernel_stages(events: list[dict], count: int, tiled: bool) -> dict:
    """Check the complete launch pattern before assigning general-entry stages."""
    padded = 1 << (count - 1).bit_length()
    sorts = 1 + max(0, padded.bit_length() - 1 - 7)
    labels = ["acceleration summary", "prediction summary", "cell keys"]
    labels += ["spatial sort"] * sorts + ["neighbour count"]
    labels += ["row prefix"] * 3 + (["tile prefix"] if tiled else [])
    labels += ["neighbour fill", "row sort"]
    labels += ["density and lambda", "lambda publication", "correction",
               "physical density check", "candidate", "plane projection"] * 8
    labels += ["velocity and containment"]
    steps = sorted((x for x in events if x["kind"] == "range" and x["name"] == "complete timestep"),
                   key=lambda x: x["start"])
    kernels = sorted((x for x in events if x["kind"] == "kernel"), key=lambda x: x["start"])
    cursor = 0
    totals: dict[str, int] = {}
    windows: dict[str, dict[str, int]] = {"1-240": {}, "241-480": {}, "481-1200": {}}
    window_counts = {name: 0 for name in windows}
    for index, step in enumerate(steps):
        batch = []
        while cursor < len(kernels) and kernels[cursor]["start"] < step["end"]:
            event = kernels[cursor]
            cursor += 1
            if event["start"] >= step["start"]:
                if event["end"] > step["end"]:
                    raise ValueError("kernel outlives accepted step")
                batch.append(event)
        if len(batch) != len(labels) or [x["name"] for x in batch[:2]] != ["observe_state"] * 2:
            raise ValueError("trace kernel sequence differs from declared workload")
        if any(x["name"] != "spatial_sort" for x in batch[3:3 + sorts]):
            raise ValueError("spatial-sort sequence differs")
        prefix = batch[4 + sorts:7 + sorts + int(tiled)]
        if any(x["name"] != "prefix_counts" for x in prefix):
            raise ValueError("prefix sequence differs")
        window = "1-240" if index < 240 else "241-480" if index < 480 else "481-1200"
        window_counts[window] += 1
        for event, label in zip(batch, labels):
            duration = event["end"] - event["start"]
            totals[label] = totals.get(label, 0) + duration
            windows[window][label] = windows[window].get(label, 0) + duration
    publication = [x for x in events if x["kind"] == "range" and x["name"] == "worker observation publication"]
    return dict(kernel_ms_per_step={k: v / 1e6 / len(steps) for k, v in sorted(totals.items())},
                windows={name: {k: v / 1e6 / window_counts[name] for k, v in values.items()}
                         for name, values in windows.items() if window_counts[name]},
                worker_publications=len(publication),
                worker_publication_ms=statistics.mean(x["end"] - x["start"] for x in publication) / 1e6
                if publication else None)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    paired = sub.add_parser("compare")
    paired.add_argument("root", type=Path)
    paired.add_argument("prefix")
    paired.add_argument("candidate")
    paired.add_argument("output", type=Path)
    trace = sub.add_parser("trace")
    trace.add_argument("database", type=Path)
    trace.add_argument("output", type=Path)
    trace.add_argument("--particles", type=int)
    trace.add_argument("--tiled", action="store_true")
    receipt = sub.add_parser("identity")
    receipt.add_argument("source", type=Path)
    receipt.add_argument("binary", type=Path)
    receipt.add_argument("output", type=Path)
    args = parser.parse_args()
    if args.action == "compare":
        result = comparison(args.root, args.prefix, args.candidate)
    elif args.action == "trace":
        events = export_timeline(args.database)
        args.output.with_suffix(".events.json").write_text(json.dumps(events, separators=(",", ":")) + "\n")
        result = timeline(events)
        if args.particles:
            result.update(kernel_stages(events, args.particles, args.tiled))
    else:
        result = identity(args.source, args.binary)
    args.output.write_text(json.dumps(result, indent=2) + "\n")


if __name__ == "__main__":
    main()
